import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const [motion, component, client] = await Promise.all([
  readFile(new URL('src/pixel-motion.js', root), 'utf8'),
  readFile(new URL('src/slider.js', root), 'utf8'),
  readFile(new URL('src/client.js', root), 'utf8'),
]);
const bundle = `// Generated by scripts/build.mjs. Edit src/ instead.\nwindow.__ModuleLoader__.load({
  id: 'dsh-claude-video-slider',
  factory(require) {
    const React = require('react');
${motion}
${component}
${client}
  }
});\n`;
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), bundle);
console.log('Built lib/client.js');
